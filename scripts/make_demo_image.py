"""Generate demo/jacket.png: a simple placeholder jacket photo.

Stdlib only (zlib + struct): dark background, jacket body, sleeves,
collar, zipper, and a price-tag block. It is intentionally a rough
placeholder for the $180-jacket demo beat — the price comes from the
question text, and the app lets you upload any real photo instead.
Source: generated by this script, no external assets.
"""

import os
import struct
import zlib

W, H = 800, 600


def _chunk(typ: bytes, data: bytes) -> bytes:
    return (
        struct.pack(">I", len(data)) + typ + data
        + struct.pack(">I", zlib.crc32(typ + data) & 0xFFFFFFFF)
    )


def _png(pixels: list[bytearray]) -> bytes:
    raw = b"".join(b"\x00" + bytes(row) for row in pixels)
    ihdr = struct.pack(">IIBBBBB", W, H, 8, 2, 0, 0, 0)
    return (
        b"\x89PNG\r\n\x1a\n"
        + _chunk(b"IHDR", ihdr)
        + _chunk(b"IDAT", zlib.compress(raw))
        + _chunk(b"IEND", b"")
    )


def _rect(px, x0, y0, x1, y1, color):
    for y in range(max(0, y0), min(H, y1)):
        for x in range(max(0, x0), min(W, x1)):
            px[y][3 * x:3 * x + 3] = bytes(color)


def main(path: str = "demo/jacket.png") -> None:
    bg = (24, 28, 36)
    jacket = (58, 68, 88)
    dark = (38, 46, 60)
    zipper = (200, 205, 215)
    tag = (240, 240, 235)
    red = (200, 60, 60)
    px = [bytearray(bg * W) for _ in range(H)]
    _rect(px, 250, 150, 550, 520, jacket)   # body
    _rect(px, 170, 170, 250, 480, dark)     # left sleeve
    _rect(px, 550, 170, 630, 480, dark)     # right sleeve
    _rect(px, 330, 110, 470, 170, dark)     # collar
    _rect(px, 396, 150, 404, 520, zipper)   # zipper
    _rect(px, 590, 120, 730, 210, tag)      # price tag
    _rect(px, 590, 120, 730, 132, red)
    _rect(px, 590, 198, 730, 210, red)
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "wb") as f:
        f.write(_png(px))
    print(f"Wrote {path} ({W}x{H})")


if __name__ == "__main__":
    main()
